def keybind_lines():
    """The `# keybind:` lines for this file (scripts/keybinds.py writes them)."""
    lines = annotations("Vishvakarma", [("app", "normal", BINDS), ("app", "insert", TYPING)])
    groups = sorted({b.seq[:2] for b in BINDS if b.seq.startswith(" ") and len(b.seq) > 2 and not b.hidden})
    names = dict(GROUPS, **OWN_GROUPS)
    lines += [f"# keybind-group: Vishvakarma/app:normal | {spell(g)} | {names.get(g, 'more').capitalize()}" for g in groups]
    return lines


def curses_token(ch):
    """A key from get_wch as a keys.py token, or None. A str is a typed
    character; an int is a key code, and an unnamed one (F1, Insert…) types
    nothing."""
    if isinstance(ch, int) and ch > 255:
        return {curses.KEY_BACKSPACE: "<BS>", curses.KEY_BTAB: "<S-Tab>", curses.KEY_UP: "<Up>",
                curses.KEY_DOWN: "<Down>", curses.KEY_LEFT: "<Left>", curses.KEY_RIGHT: "<Right>",
                curses.KEY_NPAGE: "<PgDn>", curses.KEY_PPAGE: "<PgUp>", curses.KEY_HOME: "<Home>",
                curses.KEY_END: "<End>", curses.KEY_DC: "<Del>", curses.KEY_ENTER: "<CR>"}.get(ch)
    if isinstance(ch, str):
        ch = ord(ch)
    named = {10: "<CR>", 13: "<CR>", 27: "<Esc>", 9: "<Tab>", 127: "<BS>", 8: "<BS>"}
    if ch in named:
        return named[ch]
    if 1 <= ch <= 26:
        return f"<C-{chr(ch + 96)}>"
    if 32 <= ch < 0x110000:
        return chr(ch)
    return None


